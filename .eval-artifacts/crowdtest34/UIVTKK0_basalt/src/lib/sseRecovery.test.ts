/**
 * Regression tests covering database-backed resync, restart recovery,
 * result persistence, and correlation-id semantics.
 *
 * These tests exercise the frontend state machine that mirrors the backend
 * contract: after a process restart, in-memory ring buffers are empty but the
 * DB holds terminal task rows with their result; the SSE endpoint signals
 * resync_required -> the frontend performs HTTP GET -> snapshot is applied
 * authoritatively -> final content reaches the user.
 */
import { describe, expect, it, vi } from 'vitest';
import {
  TASK_STATE_MESSAGES,
  formatTerminalTaskContent,
  isTerminalStatus,
  shouldApplyTaskEvent,
} from './taskStateSemantics';
import type { AiTask, AiTaskStatus } from './serverApi';

function makeTask(overrides: Partial<AiTask> = {}): AiTask {
  return {
    id: 'task-1',
    projectId: 'p1',
    conversationId: 'c1',
    content: 'hello',
    status: 'queued',
    createdAt: Date.now(),
    ...overrides,
  } as AiTask;
}

describe('Result persistence after process restart', () => {
  it('completed tasks carry their result through snapshot/resync', () => {
    // Scenario: server restarted, in-memory buffer empty, DB has a completed
    // row with result text. HTTP GET /api/ai/tasks returns it; frontend
    // applies as authoritative snapshot.
    const fromDb = makeTask({
      status: 'completed',
      result: '这是模型的最终回答',
      finishedAt: Date.now(),
    });

    // formatTerminalTaskContent must return the result text, not the empty placeholder
    const { content, role } = formatTerminalTaskContent(fromDb);
    expect(role).toBe('ai');
    expect(content).toBe('这是模型的最终回答');
    expect(content).not.toContain('已完成，但没有返回内容');
  });

  it('completed task with empty result falls back to explanatory message', () => {
    const fromDb = makeTask({
      status: 'completed',
      result: '',
      finishedAt: Date.now(),
    });
    const { content } = formatTerminalTaskContent(fromDb);
    expect(content).toContain('已完成');
  });

  it('queued/running tasks recovered after restart fail with restart message', () => {
    // Backend sets: status=failed, error="服务重启，任务已中断"
    const recovered = makeTask({
      status: 'failed',
      error: '服务重启，任务已中断',
      finishedAt: Date.now(),
    });
    const { content, role } = formatTerminalTaskContent(recovered);
    expect(role).toBe('system');
    expect(content).toContain('任务失败');
    expect(content).toContain('服务重启');
  });
});

describe('Resync snapshot is authoritative over stale in-memory state', () => {
  it('snapshot with completed wins over a locally-tracked queued state', () => {
    // Pre-restart we had "queued" locally; post-restart snapshot says completed.
    // shouldApplyTaskEvent would normally reject (lower precedence queued never
    // wins over completed), but authoritative:true in applyTaskUpdate bypasses
    // the guard. Verify the state machine allows it via precedence check too.
    expect(shouldApplyTaskEvent('queued', 'completed', null, Date.now())).toBe(true);
  });

  it('snapshot completed can overwrite failed if finishedAt is later', () => {
    const now = Date.now();
    // Rare but possible: snapshot reports retry success with later finishedAt
    expect(shouldApplyTaskEvent('failed', 'completed', now - 1000, now)).toBe(true);
  });

  it('late queued event after completed snapshot is rejected', () => {
    const now = Date.now();
    expect(shouldApplyTaskEvent('completed', 'queued', now, null)).toBe(false);
  });
});

describe('Correlation: taskId is the stable correlation key across all layers', () => {
  it('uses taskId as the SSE idempotency prefix', () => {
    // Simulates keys generated by makeTaskEventKey
    const key = (id: string, ev: string, seq?: string | number) =>
      seq !== undefined ? `${id}:${ev}:${seq}` : `${id}:${ev}`;

    expect(key('task-1', 'completed', 'ai-42')).toBe('task-1:completed:ai-42');
    expect(key('task-1', 'content_delta', 'ai-43')).toBe('task-1:content_delta:ai-43');
    expect(key('task-2', 'running')).toBe('task-2:running');

    // Duplicate detection: same (taskId, eventType, seq) = duplicate
    const a = key('task-1', 'completed', 'ai-42');
    const b = key('task-1', 'completed', 'ai-42');
    expect(a).toBe(b);
  });
});

describe('Unified error copy across all terminal error states', () => {
  it('has consistent user-facing Chinese messages', () => {
    expect(TASK_STATE_MESSAGES.failed.prefix).toMatch(/失败/);
    expect(TASK_STATE_MESSAGES.cancelled.prefix).toMatch(/取消/);
    expect(TASK_STATE_MESSAGES.blocked.prefix).toMatch(/阻塞/);
    expect(TASK_STATE_MESSAGES.missing.prefix).toMatch(/丢失|状态/);
    expect(TASK_STATE_MESSAGES.missing.prefix.length).toBeGreaterThan(10);
    expect(TASK_STATE_MESSAGES.resync_failed.prefix).toMatch(/同步|刷新/);
    expect(TASK_STATE_MESSAGES.scope_mismatch.prefix).toMatch(/作用域|会话/);
  });

  it('treats missing/resync_failed/scope_mismatch as terminal-error statuses', () => {
    // Completed is the only "success" terminal state.
    expect(isTerminalStatus('completed')).toBe(true);
    for (const s of ['failed', 'cancelled', 'blocked'] as AiTaskStatus[]) {
      expect(isTerminalStatus(s)).toBe(true);
    }
  });
});

describe('Restart resync flow (frontend state machine)', () => {
  /**
   * Simulate the full reconnect-after-restart sequence that the hook performs:
   *   1. Client connects with Last-Event-ID: ai-999
   *   2. Server has empty buffer (restarted) -> sends resync_required(reason=cursor_expired)
   *   3. Frontend triggers HTTP GET /api/ai/tasks (performResync)
   *   4. HTTP returns completed task with result
   *   5. applyTaskUpdate with authoritative:true finalizes the message
   */
  it('finalizes placeholder when resync delivers completed task with result', () => {
    const finalTask = makeTask({
      status: 'completed',
      result: '最终答案：42',
      finishedAt: Date.now(),
    });

    // Simulate what formatTerminalTaskContent does at the end of the resync path
    const { content, role } = formatTerminalTaskContent(finalTask);

    expect(role).toBe('ai');
    expect(content).toBe('最终答案：42');
    expect(isTerminalStatus(finalTask.status)).toBe(true);
  });

  it('surfaces resync_failed message when HTTP resync throws', () => {
    // When performResync catches, the hook calls setSseError with the
    // resync_failed prefix copy. Verify the copy is actionable.
    expect(TASK_STATE_MESSAGES.resync_failed.prefix.length).toBeGreaterThan(5);
    expect(TASK_STATE_MESSAGES.resync_failed.role).toBe('system');
  });

  it('marks missing after MISSING_TASK_TIMEOUT_MS without events', () => {
    // The collectStalePendingTaskIds helper in usePendingTaskSse emits ids
    // whose lastEventTime is older than timeout. Integration test in
    // usePendingTaskSse.test.ts already covers it; here we just verify the
    // error copy is stable.
    expect(TASK_STATE_MESSAGES.missing.role).toBe('system');
    expect(TASK_STATE_MESSAGES.missing.prefix).toMatch(/重试|刷新|连接/);
  });

  it('POST-then-SSE terminal double-apply is safe: formatTerminalTaskContent is pure/deterministic', () => {
    // When createAiTask returns a terminal task directly (sync failure / cached result),
    // useAiMessageRuntime finalizes the placeholder immediately. When SSE later
    // delivers the same completed/failed event, applyTaskUpdate re-runs with
    // formatTerminalTaskContent. The output MUST be byte-identical so the
    // second updateMessageLocally is a silent no-op from the user's POV.
    const completed = { status: 'completed' as const, result: 'final answer', error: null };
    const first = formatTerminalTaskContent(completed);
    const second = formatTerminalTaskContent(completed);
    expect(first.content).toBe(second.content);
    expect(first.role).toBe(second.role);
    expect(first.role).toBe('ai');
    expect(first.content).toBe('final answer');

    const failed = { status: 'failed' as const, result: null, error: 'boom' };
    const f1 = formatTerminalTaskContent(failed);
    const f2 = formatTerminalTaskContent(failed);
    expect(f1.content).toBe(f2.content);
    expect(f1.role).toBe('system');
    expect(f1.content).toContain('任务失败');
    expect(f1.content).toContain('boom');
  });

  it('shouldApplyTaskEvent allows idempotent re-application of same terminal with same finishedAt', () => {
    // SSE may replay the completed event on reconnect. With equal finishedAt,
    // the hook's idempotency key (seenEvents) normally dedupes, but if seentracker
    // was evicted, ordering guard must still allow the terminal event through
    // (it's idempotent — content is deterministic).
    const t = 1700000000000;
    expect(shouldApplyTaskEvent('completed', 'completed', t, t)).toBe(true);
    expect(shouldApplyTaskEvent('failed', 'failed', t, t)).toBe(true);
  });

  it('shouldApplyTaskEvent rejects older running after completed', () => {
    expect(shouldApplyTaskEvent('completed', 'running', 100, 50)).toBe(false);
  });

  it('resync_failed user message is visible and actionable (not silent)', () => {
    expect(TASK_STATE_MESSAGES.resync_failed.role).toBe('system');
    expect(TASK_STATE_MESSAGES.resync_failed.prefix).toMatch(/刷新/);
  });
});
